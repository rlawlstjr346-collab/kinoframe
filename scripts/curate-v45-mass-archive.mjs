async function politeVerifyUrls(items, cache) {
  const checks = [];
  const seen = new Set();
  for (const item of items) {
    for (const url of [item.thumbnailUrl, item.previewVideoUrl, item.sourceUrl]) {
      if (url && !seen.has(url)) {
        seen.add(url);
        checks.push({ id: item.id, url });
      }
    }
  }
  const buckets = new Map();
  for (const c of checks) {
    const host = new URL(c.url).hostname;
    if (!buckets.has(host)) buckets.set(host, []);
    buckets.get(host).push(c);
  }
  const failed = [];
  const cooled = new Set();

  await Promise.all(
    Array.from(buckets.entries()).map(async ([host, queue]) => {
      for (let i = 0; i < queue.length; i += 1) {
        if (cooled.has(host)) continue;
        if (i > 0) await sleep(randomJitterMs());
        const c = queue[i];
        const entry = cache[c.url];
        const headers = { "User-Agent": USER_AGENT, Accept: "*/*" };
        if (entry?.etag) headers["If-None-Match"] = entry.etag;
        if (entry?.lastModified) headers["If-Modified-Since"] = entry.lastModified;
        try {
          let res = await fetch(c.url, { method: "HEAD", headers, redirect: "follow" });
          if (res.status === 405 || res.status === 501) {
            res = await fetch(c.url, { method: "GET", headers: { ...headers, Range: "bytes=0-1023" }, redirect: "follow" });
          }
          if (res.body) await res.body.cancel().catch(() => {});
          if (res.status === 429 || res.status === 403) {
            cooled.add(host);
            console.warn(`[CIRCUIT-BREAKER] HTTP ${res.status} on ${host}`);
          } else if (res.status === 304 || (res.status >= 200 && res.status < 300)) {
            cache[c.url] = {
              etag: res.headers.get("etag") || entry?.etag || null,
              lastModified: res.headers.get("last-modified") || entry?.lastModified || null,
              lastCheckedAt: new Date().toISOString(),
              status: res.status,
            };
          } else {
            failed.push({ ...c, status: res.status });
          }
        } catch (err) {
          failed.push({ ...c, status: 0, error: String(err) });
        }
      }
    })
  );
  return failed;
}

async function main() {
  const verifyMode = process.argv.includes("--verify");
  const current = JSON.parse(fs.readFileSync(SNAPSHOT_PATH, "utf8"));
  const cache = fs.existsSync(CACHE_PATH) ? JSON.parse(fs.readFileSync(CACHE_PATH, "utf8")) : {};
  const tCache = fs.existsSync(TRANSLATION_CACHE_PATH) ? JSON.parse(fs.readFileSync(TRANSLATION_CACHE_PATH, "utf8")) : {};

  const replacementById = new Map(
    V45_REPLACEMENTS.map((r, i) => [r.id, expandSeed(r, i, tCache)])
  );

  // Keep KF-001..KF-232, replacing KF-131..KF-134 and remapping category overrides
  const base232 = current
    .filter((it) => {
      const n = Number(it.id.replace("KF-", ""));
      return n >= 1 && n <= 232;
    })
    .map((it) => {
      if (replacementById.has(it.id)) return replacementById.get(it.id);
      const overrideCat = REMAP_CATEGORY_OVERRIDES[it.id];
      return overrideCat ? { ...it, category: overrideCat } : it;
    });

  const seenUrls = new Set();
  for (const it of base232) {
    seenUrls.add(it.thumbnailUrl);
    seenUrls.add(it.sourceUrl);
  }

  const expandedNew = [];
  let nextNum = 233;
  for (let i = 0; i < V45_NEW_SEEDS.length; i += 1) {
    const seed = V45_NEW_SEEDS[i];
    if (seenUrls.has(seed.thumbnailUrl) || seenUrls.has(seed.sourceUrl)) continue;
    seenUrls.add(seed.thumbnailUrl);
    seenUrls.add(seed.sourceUrl);
    expandedNew.push(
      expandSeed({ ...seed, id: `KF-${String(nextNum).padStart(3, "0")}` }, i, tCache)
    );
    nextNum += 1;
  }

  if (verifyMode) {
    const toVerify = [...replacementById.values(), ...expandedNew];
    console.log(`[V4.5 CURATOR] Polite verifying ${toVerify.length} items...`);
    const failed = await politeVerifyUrls(toVerify, cache);
    if (failed.length > 0) {
      console.error("[V4.5 CURATOR] Verification failed:", failed);
      process.exit(1);
    }
    fs.writeFileSync(CACHE_PATH, JSON.stringify(cache, null, 2) + "\n", "utf8");
  }

  const merged = [...base232, ...expandedNew];
  fs.writeFileSync(SNAPSHOT_PATH, JSON.stringify(merged, null, 2) + "\n", "utf8");
  fs.writeFileSync(TRANSLATION_CACHE_PATH, JSON.stringify(tCache, null, 2) + "\n", "utf8");

  const byCat = {};
  const byCountry = {};
  const matrix = {};
  for (const item of merged) {
    byCat[item.category] = (byCat[item.category] || 0) + 1;
    byCountry[item.country] = (byCountry[item.country] || 0) + 1;
    matrix[item.category] = matrix[item.category] || {};
    matrix[item.category][item.country] = (matrix[item.category][item.country] || 0) + 1;
  }

  console.log(`[V4.5 CURATOR] Wrote ${merged.length} items (${base232.length} remapped + ${expandedNew.length} new)`);
  console.log("By Category:", byCat);
  console.log("By Country:", byCountry);
  console.table(matrix);
}

main().catch((err) => {
  console.error("[FATAL]", err);
  process.exit(1);
});
