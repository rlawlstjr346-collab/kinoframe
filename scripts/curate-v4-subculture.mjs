async function politeVerifyUrls(items) {
  const checks = [];
  const seen = new Set();
  for (const item of items) {
    for (const url of [item.thumbnailUrl, item.previewVideoUrl, item.sourceUrl]) {
      if (url && !seen.has(url)) {
        seen.add(url);
        checks.push({ id: item.id, url });
      }
    }
  }

  const buckets = new Map();
  for (const c of checks) {
    const host = new URL(c.url).hostname;
    if (!buckets.has(host)) buckets.set(host, []);
    buckets.get(host).push(c);
  }

  const failed = [];
  const cooled = new Set();

  await Promise.all(
    Array.from(buckets.entries()).map(async ([host, queue]) => {
      for (let i = 0; i < queue.length; i += 1) {
        if (cooled.has(host)) continue;
        if (i > 0) await sleep(randomJitterMs());
        const c = queue[i];
        try {
          let res = await fetch(c.url, {
            method: "HEAD",
            headers: { "User-Agent": USER_AGENT, Accept: "*/*" },
            redirect: "follow",
          });
          if (res.status === 405 || res.status === 501) {
            res = await fetch(c.url, {
              method: "GET",
              headers: { "User-Agent": USER_AGENT, Accept: "*/*", Range: "bytes=0-1023" },
              redirect: "follow",
            });
          }
          if (res.body) await res.body.cancel().catch(() => {});
          if (res.status === 429 || res.status === 403) {
            cooled.add(host);
            console.warn(`[CIRCUIT-BREAKER] HTTP ${res.status} on ${host}; cooling down.`);
          } else if (res.status < 200 || res.status >= 400) {
            failed.push({ ...c, status: res.status });
          }
        } catch (err) {
          failed.push({ ...c, status: 0, error: String(err) });
        }
      }
    })
  );

  return failed;
}

async function main() {
  const verifyMode = process.argv.includes("--verify");
  const current = JSON.parse(fs.readFileSync(SNAPSHOT_PATH, "utf8"));
  const baseItems = current.filter((it) => {
    const num = Number(it.id.replace("KF-", ""));
    return num >= 1 && num <= 124;
  });

  const remappedBase = baseItems.map(remapExistingItem);
  const existingThumbs = new Set(remappedBase.map((i) => i.thumbnailUrl));

  const newItems = V4_CURATED_SEEDS.filter(
    (s) => !existingThumbs.has(s.thumbnailUrl)
  ).map((seed, idx) => expandCuratedSeed(seed, idx));

  if (verifyMode) {
    console.log(`[V4 CURATOR] Polite verifying ${newItems.length} new items...`);
    const failed = await politeVerifyUrls(newItems);
    if (failed.length > 0) {
      console.error("[V4 CURATOR] Verification failed URLs:", failed);
      process.exit(1);
    }
  }

  const merged = [...remappedBase, ...newItems];
  fs.writeFileSync(SNAPSHOT_PATH, JSON.stringify(merged, null, 2) + "\n", "utf8");

  const byCat = {};
  const byCountry = {};
  const matrix = {};
  for (const item of merged) {
    byCat[item.category] = (byCat[item.category] || 0) + 1;
    byCountry[item.country] = (byCountry[item.country] || 0) + 1;
    matrix[item.category] = matrix[item.category] || {};
    matrix[item.category][item.country] =
      (matrix[item.category][item.country] || 0) + 1;
  }

  console.log(`[V4 CURATOR] Wrote ${merged.length} items (${remappedBase.length} remapped + ${newItems.length} new)`);
  console.log("By Category:", byCat);
  console.log("By Country:", byCountry);
  console.table(matrix);
}

main().catch((err) => {
  console.error("[FATAL]", err);
  process.exit(1);
});
