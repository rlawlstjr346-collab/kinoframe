function remapExistingItem(item) {
  let category = "PHOTO";
  if (item.mediaType === "TVCF") {
    category = "TVCF";
  } else if (item.mediaType === "PRINT") {
    category = "AD_POSTER";
  } else if (item.mediaType === "PHOTO") {
    category = "PHOTO";
  } else if (item.mediaType === "NEWS") {
    category = NEWS_TO_PHOTO.has(item.id) ? "PHOTO" : "CLASSIC_FILM";
  }

  let country = "US";
  if (JP_EXISTING.has(item.id)) country = "JP";
  else if (EU_EXISTING.has(item.id)) country = "EU";
  else if (GLOBAL_EXISTING.has(item.id)) country = "GLOBAL";

  let priorityBoost = 0;
  if (LOW_PRIORITY_EXISTING.has(item.id)) priorityBoost = -7;
  else if (HIGH_PRIORITY_EXISTING.has(item.id)) priorityBoost = 5;

  return {
    ...item,
    category,
    country,
    priorityBoost,
  };
}

